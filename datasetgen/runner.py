"""Оркестрация прогонов ``run`` / ``regenerate``.

Модуль НЕ импортирует ``engines`` на верхнем уровне и ничего не знает про
torch: работает только через :class:`datasetgen.engines.Dependencies`,
переданный вызывающим кодом (в тестах — фейки).
"""

